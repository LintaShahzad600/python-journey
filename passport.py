#Problem 1: Passport Formatter (passport.py)


#Background

#At international airports, security systems expect passenger names to be in a very specific format: UPPERCASE, with all extra whitespace removed, and spaces replaced by hyphens to prevent database glitches.

#Task

#Write a program in a file named passport.py that prompts the user for their full name. The program should then output the formatted name according to these rules:
#1. Strip any leading or trailing whitespace.
#2. Convert the entire string to uppercase.
#3. Replace all remaining spaces between words with a single hyphen (-).

#Expected Input/Output Examples


#User Input	Expected Output
 #john doe 	JOHN-DOE
#Alice Smith	ALICE-SMITH
